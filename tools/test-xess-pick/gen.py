r"""XeSS'S SETTING, PICKED BY RATIO (2026-10-28, package X2; docs/reports/xess-plan-2026-10-17, PLAN.md X2). PickXessQuality
(host/xess_host.h, between the XESS PICK PURE lines) chooses which of Intel's seven settings a build runs from the table
xessGetOptimalInputResolution answers at the output size. Held here on a bench with no device, against tables READ FROM
INTEL'S LIBRARY ON THIS MACHINE (libxess 2.0.2, an RTX 4090): X0's at 3840x2160 (docs/reports/xess-x0/SMOKE.txt) and X2's at
2560x1440, 1920x1080 and 3440x1440 (X0's tool, --output=). Each range runs from the setting's optimal input to the output size.

  the mod's five ratios at 4K (DLSS-IV.cpp, kRatio: 1.0, 2/3, 0.58, 0.5, 1/3), two custom percents (44 and 38), the mod's
  Quality at three more outputs (3440x1440's lands ONE PIXEL under Ultra Quality's least: Intel rounds its optimal size up,
  the mod rounds to nearest; X2's pipe smoke ran XeSS there, tools/test-xess/pipe.py), a table missing a setting, a size no
  range holds (the nearest, with inRange false), a render size above the output, a table where nothing answered.
THE CONTROLS: each planted wrong pick below must make the bench FAIL (a pick by name, a pick that ignores the ranges, the one
pixel taken away, the farthest instead of the nearest).

    python tools/test-xess-pick/gen.py        exit code 0 = every check passed and every control failed
"""
import os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "host", "xess_host.h")
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-test-xess-pick-%d" % os.getpid())
START = "// XESS PICK PURE START"
END = "// XESS PICK PURE END"

HEAD = r"""// GENERATED by tools/test-xess-pick/gen.py: PickXessQuality, cut from host/xess_host.h
#include <cstdio>
#include <cstring>
"""
BENCH = r"""
static int fails = 0;
static void Check(bool ok, const char* what) { printf("  %s  %s\n", ok ? "PASS" : "FAIL", what); if (!ok) fails++; }
// a table as Intel's library answered it: each setting's optimal input, its range from the optimal to the output size
struct T { XessPickRow r[7]; };
static T Table(unsigned outW, unsigned outH, const unsigned opt[7][2])
{
    static const int set[7] = { 106, 105, 104, 103, 102, 101, 100 };   // the helper's order: Native AA first
    static const char* nm[7] = { "Native Anti-Aliasing", "Ultra Quality Plus", "Ultra Quality", "Quality", "Balanced", "Performance", "Ultra Performance" };
    T t;
    for (int i = 0; i < 7; i++) t.r[i] = { set[i], nm[i], opt[i][0], opt[i][1], opt[i][0], opt[i][1], outW, outH, true };
    return t;
}
static int Pick(unsigned w, unsigned h, unsigned ow, unsigned oh, const T& t, bool* in = nullptr)
{
    const XessPick p = PickXessQuality(w, h, ow, oh, t.r, 7);
    if (in) *in = p.inRange;
    return p.index < 0 ? -1 : t.r[p.index].setting;
}
int main()
{
    // READ FROM libxess 2.0.2 on the RTX 4090 (X0's SMOKE.txt; X2's runs of X0's tool at the other three outputs)
    static const unsigned k4k[7][2]   = { {3840,2160}, {2954,1662}, {2560,1440}, {2259,1271}, {1920,1080}, {1670,940}, {1280,720} };
    static const unsigned k1440[7][2] = { {2560,1440}, {1970,1108}, {1707,960}, {1506,848}, {1280,720}, {1114,627}, {854,480} };
    static const unsigned k1080[7][2] = { {1920,1080}, {1477,831}, {1280,720}, {1130,636}, {960,540}, {835,470}, {640,360} };
    static const unsigned kUw[7][2]   = { {3440,1440}, {2647,1108}, {2294,960}, {2024,848}, {1720,720}, {1496,627}, {1147,480} };
    const T t4 = Table(3840, 2160, k4k), t14 = Table(2560, 1440, k1440), t10 = Table(1920, 1080, k1080), tuw = Table(3440, 1440, kUw);
    bool in = false;
    // the mod's five ratios at 4K, its sizes as DLSS-IV.cpp makes them (w * ratio + 0.5)
    Check(Pick(3840, 2160, 3840, 2160, t4, &in) == 106 && in, "1.0 (render scale off, native): Native Anti-Aliasing (106)");
    Check(Pick(2560, 1440, 3840, 2160, t4, &in) == 104 && in, "2/3, the mod's Quality, 2560x1440: XeSS's Ultra Quality (104), NOT its Quality: picked by ratio");
    Check(Pick(2227, 1253, 3840, 2160, t4, &in) == 102 && in, "0.58, the mod's Balanced, 2227x1253: Balanced (102); Quality's least is 2259x1271, above it");
    Check(Pick(1920, 1080, 3840, 2160, t4, &in) == 102 && in, "0.5, the mod's Performance, 1920x1080: XeSS's Balanced (102), ratio 2.0");
    Check(Pick(1280, 720, 3840, 2160, t4, &in) == 100 && in, "1/3, the mod's Ultra Performance, 1280x720: Ultra Performance (100)");
    // two custom percents
    Check(Pick(1690, 950, 3840, 2160, t4, &in) == 101 && in, "custom=44 at 4K, 1690x950 (2.27): Performance (101, 2.3)");
    Check(Pick(1459, 821, 3840, 2160, t4, &in) == 100 && in, "custom=38 at 4K, 1459x821 (2.63): Ultra Performance (100), the one range that holds it, though Performance's ratio is nearer");
    // the mod's Quality at three more outputs
    Check(Pick(1707, 960, 2560, 1440, t14, &in) == 104 && in, "the mod's Quality at 2560x1440, 1707x960: Ultra Quality (104)");
    Check(Pick(1280, 720, 1920, 1080, t10, &in) == 104 && in, "the mod's Quality at 1920x1080, 1280x720: Ultra Quality (104)");
    Check(Pick(2293, 960, 3440, 1440, tuw, &in) == 104 && in, "the mod's Quality at 3440x1440, 2293x960, ONE PIXEL under Ultra Quality's least 2294: Ultra Quality (104), held");
    Check(Pick(2227, 1253, 3840, 2160, t4) != 103, "and two pixels or more under a least is not held (the mod's Balanced is not Quality)");
    // a table missing a setting
    T miss = t4; miss.r[2].ok = false;                              // Ultra Quality did not answer
    Check(Pick(2560, 1440, 3840, 2160, miss, &in) == 103 && in, "Ultra Quality missing from the table: 2560x1440 is Quality (103), the nearest that holds it");
    T zero = t4; zero.r[2].optW = 0; zero.r[2].optH = 0;            // answered, with a zero size
    Check(Pick(2560, 1440, 3840, 2160, zero) == 103, "a row that answered a zero size is not a candidate either");
    // no range holds it
    Check(Pick(1200, 675, 3840, 2160, t4, &in) == 100 && !in, "1200x675 at 4K (3.2), below every least: the nearest, Ultra Performance, with inRange false (the helper logs it)");
    Check(Pick(3900, 2200, 3840, 2160, t4, &in) == 106 && !in, "a render size above the output: the nearest, Native Anti-Aliasing, with inRange false");
    T none = t4; for (int i = 0; i < 7; i++) none.r[i].ok = false;
    Check(Pick(2560, 1440, 3840, 2160, none) == -1, "a table where nothing answered: no pick (the helper refuses the build)");
    Check(PickXessQuality(0, 1440, 3840, 2160, t4.r, 7).index == -1 && PickXessQuality(2560, 1440, 3840, 2160, nullptr, 7).index == -1, "a zero size or no table: no pick");
    // the ratios the helper's line prints
    const XessPick q = PickXessQuality(2560, 1440, 3840, 2160, t4.r, 7);
    Check(q.ratioX > 1.4999 && q.ratioX < 1.5001 && q.optRatioX > 1.4999 && q.optRatioX < 1.5001, "the line's two ratios for the mod's Quality at 4K: 1.500 and 1.500");
    if (fails) { printf("FAIL: %d check(s)\n", fails); return 1; }
    printf("PASS\n"); return 0;
}
"""
# each must make the bench FAIL: (what, the cut's text, its replacement)
MUTANTS = [
    ("a pick that ignores the ranges (the nearest ratio wins outright)", "if (holds && d < heldD)", "if ((holds || true) && d < heldD)"),
    ("the one pixel taken away", "const bool holds = w + 1 >= r.minW && w <= r.maxW && hh + 1 >= r.minH && hh <= r.maxH;",
     "const bool holds = w >= r.minW && w <= r.maxW && hh >= r.minH && hh <= r.maxH;"),
    ("the farthest instead of the nearest", "if (holds && d < heldD) { heldD = d; held = i; }", "if (holds && (held < 0 || d > heldD)) { heldD = d; held = i; }"),
    ("only a size exactly a setting's optimal is held", "const bool holds = w + 1 >= r.minW && w <= r.maxW && hh + 1 >= r.minH && hh <= r.maxH;",
     "const bool holds = w == r.optW && hh == r.optH;"),
]


def build_run(name, text, vcvars):
    d = os.path.join(OUT, name); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "pick.cpp"), "w", encoding="utf-8") as f: f.write(HEAD + text + BENCH)
    r = subprocess.run('call "%s" >nul 2>&1 && cl /nologo /EHsc /W4 /WX /std:c++17 /O2 pick.cpp /Fe:pick.exe' % vcvars, shell=True, capture_output=True, text=True, cwd=d)
    if r.returncode != 0: return None, r.stdout[-3000:] + r.stderr[-1000:]
    r = subprocess.run([os.path.join(d, "pick.exe")], capture_output=True, text=True)
    return r.returncode, r.stdout


def main():
    src = open(SRC, encoding="utf-8").read().replace("\r\n", "\n")
    if src.count(START) != 1 or src.count(END) != 1: print("FAIL: the XESS PICK PURE lines are not in host/xess_host.h exactly once"); return 1
    a = src.index(START); b = src.index(END, a)
    cut = src[a:b]
    os.makedirs(OUT, exist_ok=True)
    vsw = os.path.expandvars(r"%ProgramFiles(x86)%\Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars64.bat")
    rc, out = build_run("pick", cut, vcvars)
    if rc is None: print(out); print("FAIL: the cut did not compile"); return 1
    print(out, end="")
    fails = 1 if rc else 0
    for i, (what, old, new) in enumerate(MUTANTS):
        if cut.count(old) != 1: print("  FAIL  control cannot be planted (%d x): %s" % (cut.count(old), what)); fails += 1; continue
        mrc, mout = build_run("m%d" % i, cut.replace(old, new), vcvars)
        ok = mrc is not None and mrc != 0
        named = [l.strip()[6:] for l in (mout or "").splitlines() if l.strip().startswith("FAIL  ")]
        print("  %s  control: %s -> the bench fails%s" % ("PASS" if ok else "FAIL", what, (" (%d check(s), the first: %s)" % (len(named), named[0][:90])) if named else ""))
        if not ok: fails += 1
    # THE HELPER CALLS IT AS THE BENCH DOES: the table filled from Intel's answer, the seven settings, the pick, the setting given to Init
    body = src[src.index("static bool XessBuildContext("):src.index("// ---------------------------------------------------------------------------------------------------------- teardown")]
    order = ["XOP_OPTIMAL", "rows[i] = { (int)kSet[i].q, kSet[i].name, opt.x, opt.y, mn.x, mn.y, mx.x, mx.y, r == XESS_RESULT_SUCCESS };",
             "PickXessQuality(w, hh, outW, outH, rows, kN)", "ip.qualitySetting   = (xess_quality_settings_t)pr.setting;", "XOP_INIT"]
    at, ok = -1, True
    for p in order:
        at = body.find(p, at + 1)
        if at < 0: ok = False; break
    print("  %s  XessBuildContext fills the table from Intel's answer (min and max as the library gives them), picks, and hands the pick to xessD3D12Init" % ("PASS" if ok else "FAIL"))
    if not ok: fails += 1
    n7 = sum(body.count("XESS_QUALITY_SETTING_%s," % s) for s in ("AA", "ULTRA_QUALITY_PLUS", "ULTRA_QUALITY", "QUALITY", "BALANCED", "PERFORMANCE", "ULTRA_PERFORMANCE"))
    print("  %s  all seven of Intel's settings are asked (%d named)" % ("PASS" if n7 == 7 else "FAIL", n7))
    if n7 != 7: fails += 1
    print("FAIL" if fails else "PASS")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
