"""THE FLIP CLASSIFIER'S PROOF OF ARITHMETIC (2026-09-24, frame generation phase 1B, instrument I-B2; the classifier spec's
checklist items 6 and 11). The reference model (synth-sim.py, variant V2, run here with --dump) writes every synthetic window
it classifies, frame by frame; the classifier's C code is cut from source/DLSS-IV.cpp (from "THE FLIP CLASSIFIER" to the
waiter's loop, never copied by hand), compiled into harness.cpp as a 32-bit program with the mod's own compiler flags (build.ps1:
cl /MT /GS /EHa /W3 /std:c++17 /O2, x86, WIN32 and _WINDOWS), once as a release build (DLSSIV_DEVLOG 0) and once as a
development one (1), and fed every dumped window. Every verdict and every display memory must match the model's. Then the
log=1 test: a change line by window 2 on the model's first cell, and on a feed that never settles the liveness line at
window 30 and none before.

(2026-09-24, the classifier's verification) The dump holds every window's key constant, so both builds also run
harness --key: hand-made feeds for the key's clears (a Reset, vsync and the refresh, between windows and inside one), the
latch, the pacer's share, every cap channel with Custom -n rounded and truncated, a 120000/1001 refresh and a resync inside
a window, each with the rule's answer. A second control drops the straddle guard (LatFlipStep, at the key), which --key must
see.

    python tools/flipcls/run.py          builds, dumps, replays; exit code 0 = everything matched and the log and key tests passed

Needs numpy (the model) and the Visual Studio the build uses (vswhere finds it). Works in %TEMP%\\dlssiv-flipcls-<pid>, removed
when everything passes and kept to read when anything fails.
"""
import os, sys, subprocess, tempfile, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CPP = os.path.join(ROOT, "source", "DLSS-IV.cpp")
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-flipcls-%d" % os.getpid())
START = "// ---- THE FLIP CLASSIFIER ----"
END = "// THE LATENCY WAITER'S LOOP"


def cut():
    src = open(CPP, "rb").read().decode("latin-1")
    a = src.find(START); z = src.find(END, a)
    if a < 0 or z < 0: raise SystemExit("the classifier's block was not found in %s (markers %r, %r)" % (CPP, START, END))
    return "// GENERATED by tools/flipcls/run.py: cut from source/DLSS-IV.cpp, not edited.\r\n" + src[a:z]


def main():
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "flip_extract.h"), "wb").write(cut().encode("latin-1"))
    shutil.copy(os.path.join(HERE, "harness.cpp"), OUT)
    dump = os.path.join(OUT, "windows.txt")
    print("the model, V2, --dump:")
    r = subprocess.run([sys.executable, os.path.join(HERE, "synth-sim.py"), "--dump", dump], capture_output=True, text=True)
    if r.returncode: print(r.stdout[-2000:], r.stderr[-2000:]); return 1
    print("  " + [l for l in r.stdout.splitlines() if l.startswith("DUMP ")][-1])
    vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")
    fails = 0
    for devlog in (0, 1):
        exe = "harness_%d.exe" % devlog
        cmd = 'call "%s" >nul 2>&1 && cl /nologo /MT /GS /EHa /W3 /std:c++17 /O2 /DWIN32 /D_WINDOWS /DDLSSIV_DEVLOG=%d harness.cpp /Fe:%s /Fo:harness_%d.obj' % (vcvars, devlog, exe, devlog)
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=OUT)   # a string through the shell, as tools/test-ladder does
        warn = [l for l in r.stdout.splitlines() if "warning" in l or "error" in l]
        print("the C code, %s build (DLSSIV_DEVLOG %d): %s" % ("release" if devlog == 0 else "development", devlog, "compiled" if r.returncode == 0 else "DID NOT COMPILE"))
        for l in warn[:10]: print("  " + l)
        if r.returncode: print(r.stdout[-3000:]); fails += 1; continue
        r = subprocess.run([os.path.join(OUT, exe), dump], capture_output=True, text=True)
        print(r.stdout.rstrip()); fails += 1 if r.returncode else 0
        print("the key and channel feeds (%s build):" % ("release" if devlog == 0 else "development"))
        r = subprocess.run([os.path.join(OUT, exe), "--key"], capture_output=True, text=True)
        print(r.stdout.rstrip()); fails += 1 if r.returncode else 0
        if devlog == 0:
            print("the log=1 test (release build):")
            r = subprocess.run([os.path.join(OUT, exe), "--log", dump], capture_output=True, text=True)
            print(r.stdout.rstrip()); fails += 1 if r.returncode else 0
    # THE CONTROL: the same replay must SEE a change. One threshold of the cut code moved (FREE's phase-lock bound, 0.40 to
    # 0.30), compiled the same way: the replay has to report differing verdicts, or it measured nothing.
    ctl = cut()
    moved = ctl.replace("R <= 0.40 && nA >= 60", "R <= 0.30 && nA >= 60")
    if moved == ctl: print("the control: the marker line for FREE's bound was not found"); fails += 1
    else:
        os.makedirs(os.path.join(OUT, "control"), exist_ok=True)
        open(os.path.join(OUT, "control", "flip_extract.h"), "wb").write(moved.encode("latin-1"))
        shutil.copy(os.path.join(HERE, "harness.cpp"), os.path.join(OUT, "control"))
        cmd = 'call "%s" >nul 2>&1 && cl /nologo /MT /GS /EHa /W3 /std:c++17 /O2 /DWIN32 /D_WINDOWS /DDLSSIV_DEVLOG=0 harness.cpp /Fe:harness_ctl.exe' % vcvars
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=os.path.join(OUT, "control"))
        r = subprocess.run([os.path.join(OUT, "control", "harness_ctl.exe"), dump], capture_output=True, text=True)
        last = [l for l in r.stdout.splitlines() if "replayed" in l]
        print("the control (FREE's bound moved to 0.30, which must be seen): " + (last[-1].strip() if last else "no replay line"))
        if r.returncode == 0: print("  THE CONTROL PASSED, SO THE REPLAY CANNOT SEE A CHANGE"); fails += 1
    # THE SECOND CONTROL (2026-09-24): the straddle guard dropped, so a window that straddles a Reset or a vsync change feeds
    # the memory and the latch again. --key must fail on it, or its straddle feeds measured nothing.
    guard = "if (straddle) { pin = false; memok = false; }"
    dropped = ctl.replace(guard, "if (false) { pin = false; memok = false; }")
    if dropped == ctl: print("the second control: the straddle guard was not found"); fails += 1
    else:
        os.makedirs(os.path.join(OUT, "control2"), exist_ok=True)
        open(os.path.join(OUT, "control2", "flip_extract.h"), "wb").write(dropped.encode("latin-1"))
        shutil.copy(os.path.join(HERE, "harness.cpp"), os.path.join(OUT, "control2"))
        cmd = 'call "%s" >nul 2>&1 && cl /nologo /MT /GS /EHa /W3 /std:c++17 /O2 /DWIN32 /D_WINDOWS /DDLSSIV_DEVLOG=0 harness.cpp /Fe:harness_ctl2.exe' % vcvars
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=os.path.join(OUT, "control2"))
        if r.returncode: print("the second control DID NOT COMPILE"); print(r.stdout[-3000:]); fails += 1
        else:
            r = subprocess.run([os.path.join(OUT, "control2", "harness_ctl2.exe"), "--key"], capture_output=True, text=True)
            bad = [l.strip() for l in r.stdout.splitlines() if l.strip().startswith("FAIL")]
            print("the second control (the straddle guard dropped, which --key must see): %d expectations failed%s" % (len(bad), "".join("\n  " + l for l in bad[:6])))
            if r.returncode == 0: print("  THE SECOND CONTROL PASSED, SO THE KEY FEEDS CANNOT SEE A STRADDLE"); fails += 1
    print("FLIPCLS %s" % ("PASS: every verdict and every memory matched the model's, in both builds, and the log and key tests passed" if not fails else "FAIL (%d)" % fails))
    if not fails: shutil.rmtree(OUT, ignore_errors=True)
    else: print("kept for reading: " + OUT)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
