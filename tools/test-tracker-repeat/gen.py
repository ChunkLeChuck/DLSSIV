"""THE TRACKER'S REPEAT RULE, AT A DESK (2026-10-11). Not shipped; no Direct3D.

    python tools\\test-tracker-repeat\\gen.py            builds and runs; exit code 0 = every check passed

The tracker (source\\DLSS-IV.cpp, from `struct ObjKey` to the end of M4dEndFrame: the exact table, the unmatched lists,
M4dNoteDraw, M4dEndFrame) is CUT from the source, never copied, and driven by frames made here: a mesh, a world
matrix, a pose, draw after draw, as the game hands them over. Stand-ins only for what the tracker asks of the rest of
the mod (the pose store answers a row for a pose's hash; the side answers the frame and the search window).
WHAT IS HELD:
  - a character carried along (its world moves every frame) whose hair is SIX draws of one mesh a frame: every one of
    the six is given LAST frame's world and LAST frame's pose row, the same as the first (until 2026-10-11 the five
    repeats were given THIS frame's world: the hair moved like a point standing still in the world);
  - CONTROL: the cut with the repeat's branch taken out fails exactly that;
  - a character standing still, animating: all six are given this frame's world and last frame's pose, as before;
  - a character that moves and then stops: the frame it stops, the note left the frame before is not read;
  - a character seen for the first time: no previous transform, for the first draw and for the repeats;
  - a rigid mesh drawn twice in a frame: the second draw is not a mover, as before.
"""
import os, re, subprocess, sys, tempfile, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
cpp = open(os.path.join(ROOT, "source", "DLSS-IV.cpp"), "rb").read().decode("utf-8").replace("\r\n", "\n")
a = cpp.index("struct ObjKey\n{"); e0 = cpp.index("static void M4dEndFrame()", a); b = cpp.index("\n}\n", e0) + 3
cut = cpp[a:b]
BRANCH = "            if (e.lastMoved == S::Frames() && !e.hasBone && e.boneHash != 0)\n            {"
assert cut.count(BRANCH) == 1, "the repeat's branch is not where this test looks for it"

PRELUDE = r'''// GENERATED by tools/test-tracker-repeat/gen.py: the tracker below is cut from source/DLSS-IV.cpp.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <intrin.h>
#include <xmmintrin.h>
#include <cstdio>
#include <cstring>
#include <cmath>
#define DLSSIV_HOT
#define DLSSIV_TRKLINE
#define DLSSIV_DEVLOG 0
#define DLSSIV_M4D_INDEX_VERIFY 0
#define DEVSTAT(...)
static bool telemetryOn = false, censusOn = false;
static void LogRecord(const char*, ...) {}
static void LogDetail(const char*, ...) {}
static void LogHealth(const char*, ...) {}
// what the tracker asks of the rest of the mod
static LONG   gFrame = 10;
static float  gWorld[16];
static unsigned __int64 gSerial = 1;
static unsigned gPose = 0;                     // the hash of the bones bound now
static UINT_PTR gVB = 0, gIB = 0;
static bool PrevBonesLive() { return true; }
template<class S> static unsigned HashBones() { return gPose; }
template<class S> static int BoneStoreAlloc(unsigned poseHash, bool dedupe = true) { (void)dedupe; return (int)(poseHash & 1023u); }   // a row a pose
struct Side
{
    static const float* World()       { return gWorld; }
    static unsigned __int64 WorldSerial() { return gSerial; }     // bumped with every world upload, as the mod bumps it: the tracker memoises the world's hash by it
    static UINT_PTR VBKey()           { return gVB; }
    static UINT_PTR IBKey()           { return gIB; }
    static float    Window()          { return 2.0f; }
    static LONG     Frames()          { return gFrame; }
};
// ---------------------------------------------------------------- the tracker, as shipped
'''
BENCH = r'''
// ---------------------------------------------------------------- the bench
static int fails = 0;
static void Check(bool ok, const char* what) { printf("  %s  %s\n", ok ? "ok  " : "FAIL", what); if (!ok) fails++; }
static void World(float x) { gSerial++; memset(gWorld, 0, sizeof(gWorld)); gWorld[0] = gWorld[5] = gWorld[10] = gWorld[15] = 1.0f; gWorld[12] = x; gWorld[13] = 100.0f; gWorld[14] = 5.0f; }
struct Got { bool mover; float px; int row; };
static Got Draw(UINT_PTR vb, UINT prims, bool skinned)
{
    gVB = vb; gIB = vb + 1;
    float prev[16]; int row = -7; memset(prev, 0, sizeof(prev));
    Got g; g.mover = M4dNoteDraw<Side>(0, 0, prims, gWorld, prev, skinned, &row); g.px = prev[12]; g.row = row;
    return g;
}
static void EndFrame() { M4dEndFrame(); gFrame++; }
int main()
{
    const UINT_PTR HAIR = 0x1000, HEAD = 0x2000, CRATE = 0x3000, NEW = 0x4000;
    // 1. CARRIED ALONG: the world moves half a unit a frame, the pose changes every frame, the hair is six draws
    Got hair[6], head; bool all = true, first = true; int rowBefore = -1;
    for (int f = 0; f < 6; f++)
    {
        World(10.0f + 0.5f * f); gPose = 0x100u + (unsigned)f;
        head = Draw(HEAD, 900, true);
        for (int i = 0; i < 6; i++) hair[i] = Draw(HAIR, 382, true);
        if (f >= 2)
        {
            const float wantX = 10.0f + 0.5f * (f - 1); const int wantRow = (int)((0x100u + (unsigned)(f - 1)) & 1023u);
            if (!(head.mover && fabsf(head.px - wantX) < 1e-4f && head.row == wantRow)) first = false;
            if (!(hair[0].mover && fabsf(hair[0].px - wantX) < 1e-4f && hair[0].row == wantRow)) first = false;
            for (int i = 1; i < 6; i++) if (!(hair[i].mover && fabsf(hair[i].px - wantX) < 1e-4f && hair[i].row == wantRow)) all = false;
            rowBefore = wantRow;
        }
        EndFrame();
    }
    printf("  the last frame: the head previous x %.2f row %d; the hair's six draws previous x %.2f %.2f %.2f %.2f %.2f %.2f, rows %d %d %d %d %d %d (this frame's x is %.2f)\n",
           head.px, head.row, hair[0].px, hair[1].px, hair[2].px, hair[3].px, hair[4].px, hair[5].px, hair[0].row, hair[1].row, hair[2].row, hair[3].row, hair[4].row, hair[5].row, gWorld[12]);
    Check(first, "carried along: the head, and the hair's FIRST draw, are given last frame's world and last frame's pose (the proximity match)");
    Check(all, "carried along: the hair's five REPEATS are given the same, not this frame's world");
    (void)rowBefore;
    // 2. STANDING STILL, ANIMATING: the world does not change, the pose does
    bool still = true;
    for (int f = 0; f < 4; f++)
    {
        World(12.5f); gPose = 0x200u + (unsigned)f;       // where the last moving frame left it
        for (int i = 0; i < 6; i++) hair[i] = Draw(HAIR, 382, true);
        if (f >= 2) for (int i = 0; i < 6; i++)
            if (!(hair[i].mover && fabsf(hair[i].px - 12.5f) < 1e-4f && hair[i].row == (int)((0x200u + (unsigned)(f - 1)) & 1023u))) still = false;
        EndFrame();
    }
    Check(still, "standing still and animating: all six are given this frame's world and last frame's pose, as before");
    // 3. MOVES, THEN STOPS: the frame it stops, the first draw hits the entry made while it moved; the note on it is a frame old
    World(20.0f); gPose = 0x300u; for (int i = 0; i < 6; i++) Draw(HAIR, 382, true); EndFrame();
    World(20.5f); gPose = 0x301u; for (int i = 0; i < 6; i++) Draw(HAIR, 382, true); EndFrame();
    World(20.5f); gPose = 0x302u; bool stop = true;
    for (int i = 0; i < 6; i++) { hair[i] = Draw(HAIR, 382, true); if (hair[i].mover && fabsf(hair[i].px - 20.5f) > 1e-4f) stop = false; if (hair[i].mover != hair[0].mover || hair[i].row != hair[0].row) stop = false; }
    Check(stop && hair[0].mover && hair[0].row == (int)(0x301u & 1023u), "moves, then stops: the frame it stops every draw is given this frame's world and last frame's pose; a note a frame old is not read");
    EndFrame();
    // 4. SEEN FOR THE FIRST TIME: no history, for the first draw and the repeats alike
    World(500.0f); gPose = 0x400u; bool fresh = true;
    for (int i = 0; i < 6; i++) { Got g = Draw(NEW, 77, true); if (g.mover) fresh = false; }
    Check(fresh, "seen for the first time: no previous transform, for the first draw and for the five repeats");
    EndFrame();
    // 5. A RIGID MESH DRAWN TWICE IN A FRAME, moving
    World(30.0f); Draw(CRATE, 12, false); Draw(CRATE, 12, false); EndFrame();
    World(30.5f); const Got c1 = Draw(CRATE, 12, false), c2 = Draw(CRATE, 12, false);
    Check(c1.mover && fabsf(c1.px - 30.0f) < 1e-4f && !c2.mover, "a rigid mesh drawn twice in a frame: the first is the mover, the second is not one, as before");
    if (fails) { printf("FAIL: %d check(s)\n", fails); return 1; }
    printf("PASS\n"); return 0;
}
'''
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-test-tracker-repeat-%d" % os.getpid()); os.makedirs(OUT, exist_ok=True)
vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")


def build_run(text, name):
    open(os.path.join(OUT, name + ".cpp"), "w", encoding="utf-8", newline="\n").write(PRELUDE + text + BENCH)
    r = subprocess.run('call "%s" >nul 2>&1 && cl /nologo /EHsc /W3 /std:c++17 /O2 %s.cpp /Fe:%s.exe' % (vcvars, name, name), shell=True, capture_output=True, text=True, cwd=OUT)
    if r.returncode or not os.path.exists(os.path.join(OUT, name + ".exe")): return None, r.stdout[-3500:]
    r = subprocess.run([os.path.join(OUT, name + ".exe")], capture_output=True, text=True)
    return r.returncode, r.stdout


rc, out = build_run(cut, "tr")
print(out, end="")
if rc is None: print("COMPILE FAILED"); sys.exit(2)
fails = 1 if rc else 0
# THE CONTROL: the same cut with the repeat's branch never taken
spoiled = cut.replace(BRANCH, BRANCH.replace("e.boneHash != 0)", "e.boneHash != 0 && false)"))
rc2, out2 = build_run(spoiled, "tr_control")
bad = [l.strip() for l in (out2 or "").splitlines() if l.strip().startswith("FAIL  ")]
ok = rc2 == 1 and len(bad) == 1 and "five REPEATS" in bad[0]
print("  %s  CONTROL: with the repeat's branch never taken, exactly the repeats' check fails (%s)" % ("ok  " if ok else "FAIL", "; ".join(b[6:70] for b in bad) or "nothing failed"))
if not ok: fails += 1
print("FAIL" if fails else "PASS (the whole of it)")
if not fails: shutil.rmtree(OUT, ignore_errors=True)
sys.exit(1 if fails else 0)
