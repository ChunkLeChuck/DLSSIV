"""THE REFRESH GUARD'S BENCH TEST (2026-09-26). The guard (RgSetRefresh and RgStep, at the end of
source/DLSS-IV.cpp, after DllMain) decides from present times alone, so it can be compiled on its own and driven by
synthetic ones: presents that vsync holds (with hitches and queue refills), presents that outrun the refresh, frames that
slow down, jitter, a pause, low and odd refreshes. Every case the card cannot stage on demand is reached here, on the
SHIPPED code: the logic is cut out of the header at test time, never copied.

    python tools/test-refresh-guard/gen.py            builds and runs; exit code 0 = every check passed
    python tools/test-refresh-guard/gen.py -v         also prints every log line the guard wrote

Needs the same Visual Studio the build uses (vswhere finds it). Writes into %TEMP%\\dlssiv-test-rg-<pid> (removed when it passes, kept to read when it fails).
"""
import os, sys, subprocess, tempfile, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "source", "DLSS-IV.cpp")
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-test-rg-%d" % os.getpid())
START = "// THE REFRESH GUARD ("
END = "// END OF THE REFRESH GUARD'S LOGIC"

PRELUDE = r'''// GENERATED by tools/test-refresh-guard/gen.py: the guard below is cut from source/DLSS-IV.cpp.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <cstdio>
#include <cstdarg>
#include <string>
#include <vector>
static bool gVerbose = false;
static int  gRecords = 0, gHealths = 0;
static std::string gLast;
static void LogRecord(const char* fmt, ...)
{
    char b[800]; va_list ap; va_start(ap, fmt); _vsnprintf_s(b, sizeof(b), _TRUNCATE, fmt, ap); va_end(ap);
    gRecords++; gLast = b; if (gVerbose) printf("   [log=1] %s\n", b);
}
static void LogHealth(const char* fmt, ...)
{
    char b[800]; va_list ap; va_start(ap, fmt); _vsnprintf_s(b, sizeof(b), _TRUNCATE, fmt, ap); va_end(ap);
    gHealths++; gLast = b; if (gVerbose) printf("   [log=2] %s\n", b);
}
// ---------------------------------------------------------------- the guard, as shipped
'''

def main():
    verbose = "-v" in sys.argv
    src = open(SRC, "rb").read().decode("utf-8")
    a = src.index(START); b = src.index(END, a)
    block = src[a:b]
    bench = open(os.path.join(HERE, "bench.inc"), "rb").read().decode("utf-8")
    os.makedirs(OUT, exist_ok=True)
    cpp = os.path.join(OUT, "test_rg.cpp")
    open(cpp, "wb").write((PRELUDE + block + "\n// ---------------------------------------------------------------- the bench\n" + bench).encode("utf-8"))
    vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")
    exe = os.path.join(OUT, "test_rg.exe")
    cmd = 'call "%s" >nul 2>&1 && cl /nologo /EHsc /W3 /std:c++17 /O2 test_rg.cpp /Fe:test_rg.exe' % vcvars
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=OUT)
    if r.returncode != 0 or not os.path.exists(exe) or "warning C" in r.stdout:
        print(r.stdout); print(r.stderr); print("COMPILE FAILED (exit %d)" % r.returncode); return 2
    r = subprocess.run([exe] + (["-v"] if verbose else []), capture_output=True, text=True)
    print(r.stdout, end="")
    if r.stderr: print(r.stderr, end="")
    return r.returncode

if __name__ == "__main__":
    rc = main()
    if rc == 0: shutil.rmtree(OUT, ignore_errors=True)
    sys.exit(rc)
