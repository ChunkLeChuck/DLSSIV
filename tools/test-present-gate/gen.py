"""THE GATE BEFORE DXVK'S PRESENT, AT A DESK (2026-10-10). The gate's state, term and core (source/transport/present_gate.h)
touch no global of the mod: they are a function of what they are handed, and feed_vk.h reaches Vulkan through a table of
pointers. So this program compiles the SHIPPED header (IVT_GATE_CORE_ONLY: the three pieces alone, nothing copied) over a
made-up Vulkan whose two fences this file moves, and holds the core to its rules: the previous-present rule, a counter
of 0 as a value, a failed read, a failed wait, the going-down flag, the second need, the cap, and what a present that
is not held costs in calls. No graphics device, no window, no helper.

THE LATENCY WAITER'S WAIT rides along (LatWaitIn, cut from the end of source/DLSS-IV.cpp, never copied): a wait for a
frame more than two past the last one sent answers "timed out" with no call of the driver, after the wait's own time,
and at once when the waiter is being stopped; anything nearer is the real wait.

    python tools/test-present-gate/gen.py            builds and runs; exit code 0 = every check passed
    python tools/test-present-gate/gen.py -v         also prints every check
    python tools/test-present-gate/gen.py --no-cap   leaves out the one case that takes the cap's 8 seconds
    python tools/test-present-gate/gen.py --no-controls   the shipped header alone

THE CONTROLS. A bench that cannot fail proves nothing, so after the shipped header has passed, the same bench is built
over four copies of it with ONE rule broken in each (the faults a review of the first gate found, and the ones this
port could make), and each must FAIL: a counter of 0 taken for unread; this present's need in place of the previous
one's; the need not stored; a failed wait ignored. A fifth breaks the waiter's wait (one past in place of two).

What it cannot show is the freeze itself (DXVK, a driver and a stalled helper): that is the frame generation branch's
desk reproduction, which runs this same core on real fences.

Needs the same Visual Studio the build uses (vswhere finds it). Writes into %TEMP%\\dlssiv-test-gate-<pid> (removed when it
passes, kept to read when it fails).
"""
