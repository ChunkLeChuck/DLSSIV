"""THE PER-GAME G-SYNC READ, RUN AGAINST THE INSTALLED DRIVER (2026-09-27). The mod reads NVIDIA's per-game G-Sync setting
for GTA IV once, at DXVK's first instance, and keeps DXVK's name in SDR when it is switched off (IvtGsyncRead and
HdrDecideOnce, after DllMain in source/DLSS-IV.cpp). This cuts the reading out of the SHIPPED source, compiles it for x86
like the mod, and runs it under the name GTAIV.exe, so the driver answers it from GTA IV's profile as it would answer the
game right now. Read-only: nothing in the driver's settings is changed.

    python tools/test-gsync-read/gen.py      exit 0 when every call the reading needs answered

NOT IN prove-all: the answer depends on this machine's driver and on the NVIDIA settings of the moment, which is the
point (it is run with the setting in a known state: the kit's X1 forces it off for GTA IV, PERF R puts it back).
Needs the same Visual Studio the build uses (vswhere finds it). Writes into %TEMP%\\dlssiv-test-gsync-<pid>.
"""
import os, sys, subprocess, tempfile, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "source", "DLSS-IV.cpp")
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-test-gsync-%d" % os.getpid())
START = "// THE PER-GAME G-SYNC SWITCH ("
END = "// END OF THE PER-GAME G-SYNC READ"

PRELUDE = r'''// GENERATED by tools/test-gsync-read/gen.py: the reading below is cut from source/DLSS-IV.cpp.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <cstdio>
#include <cstring>
#include <cstdarg>
// stand-ins for what the cap's rule (LatNvCapSeen) touches of the mod: the limiter flag, its note, the log, the cap kept
static struct { bool limiter; } latFlags;
#define latLimiter (latFlags.limiter)
static char     latLimiterNote[240] = "";
static unsigned latNvCapFps = 0;
static int      latNvCapLoc = -1;
static char     latNvCapNote[96] = "";
static char     g_logged[4][300]; static int g_loggedN = 0;
static void LogRecord(const char* fmt, ...) { va_list ap; va_start(ap, fmt); if (g_loggedN < 4) vsnprintf(g_logged[g_loggedN++], sizeof(g_logged[0]), fmt, ap); va_end(ap); }
// ---------------------------------------------------------------- the reading, as shipped
'''
MAIN = r'''
// ---------------------------------------------------------------- the bench: this exe is named GTAIV.exe, so the reading's
// GetModuleFileNameW gives the driver a GTAIV.exe to find, as the game's own call does.
int main()
{
    wchar_t me[MAX_PATH] = L""; GetModuleFileNameW(nullptr, me, MAX_PATH);
    IvtGsyncRead();
    const IvtGsyncState& g = ivtGsync;
    printf("as %ls\n", me);
    if (!g.read) { printf("NOT READ: %s (%u ms)\n", g.why, g.ms); return 1; }
    printf("read in %u ms; game profile of its own: %d\n", g.ms, (int)g.gameProfile);
    printf("VRR_APP_OVERRIDE 0x10A879CF = %u (location %d)\n", g.appOverride, g.locOverride);
    printf("VRR_APP_OVERRIDE_REQUEST_STATE 0x10A879AC = %u (location %d)\n", g.request, g.locRequest);
    printf("VRR_MODE 0x1194F158 = %u for the game, %u in the global profile (the display)\n", g.gameMode, g.globalMode);
    printf("DECISION (IvtGsyncOffForGame, as shipped; a per-game switch counts only while the display's G-Sync is on): %s\n", IvtGsyncOffForGame(g) ? "G-Sync SWITCHED OFF for GTA IV: SDR keeps \"DXVK\", HDR warns" : "G-Sync allowed for GTA IV: SDR renames");
    printf("VSYNCMODE 0x00A879CF = 0x%08X, %s (location %d)\n", g.vsyncMode, IvtVsyncModeName(g.vsyncMode), g.locVsync);
    printf("FRL_FPS 0x10835002 (Max Frame Rate) = %u%s (location %d: %s)\n", g.frl, g.frl ? " fps: A CAP THE MOD NOW SEES" : ", no cap", g.locFrl, IvtSettingWhereName(g.locFrl));
    printf("NvAPI_Disp_GetVRRInfo, the primary display: variable refresh possible %d, the display in VRR mode %d (-1: the driver did not answer); in the log's words: %s\n", g.vrrPossible, g.vrrInMode, IvtVrrText(g));   // IvtVrrText is in the cut since the log's long line was split (2026-10-10) and nothing here named it: the harness stopped compiling without a word
    printf("DECISION (IvtDriverVsyncOnFixedRefresh, 2026-10-02: the driver forces vsync AND no variable refresh is in play): %s\n", IvtDriverVsyncOnFixedRefresh(g) ? "YES: SDR keeps \"DXVK\"" : "no: SDR renames");
    // THE RULE ON MADE-UP STATES (the machine above shows one row of it): forced and passive, with and without variable refresh.
    struct { unsigned vs; unsigned mode; int possible; bool want; const char* what; } const k[] = {
        { 0x47814940u, 0, 1, true,  "forced on, G-Sync unticked for the display" },
        { 0x47814940u, 1, 0, true,  "forced on, a monitor without variable refresh" },
        { 0x32610244u, 1, 0, true,  "half refresh, a monitor without variable refresh" },
        { 0x47814940u, 2, 1, false, "forced on, G-Sync on (a common G-Sync setup): renamed" },
        { 0x47814940u, 1, -1, false, "forced on, the driver did not say: renamed, as before the rule" },
        { 0x60925292u, 0, 0, false, "the application decides, no variable refresh: renamed (the kit's E4 and N6 held 60)" },
        { 0x08416747u, 0, 0, false, "forced off, no variable refresh: renamed" },
        { 0x18888888u, 0, 0, false, "Fast Sync, no variable refresh: not counted" },
    };
    int bad = 0;
    for (const auto& c : k)
    {
        IvtGsyncState t = {}; t.read = true; t.vsyncMode = c.vs; t.globalMode = c.mode; t.vrrPossible = c.possible;
        const bool got = IvtDriverVsyncOnFixedRefresh(t);
        printf("  %s  %s -> %s\n", got == c.want ? "ok  " : "FAIL", c.what, got ? "keeps \"DXVK\"" : "renames");
        if (got != c.want) bad++;
    }
    // NVIDIA'S FRAME RATE CAP AS A LIMITER THE MOD SEES (LatNvCapSeen, as shipped): made-up readings, the rule's own text
    {
        struct { const char* what; bool read; unsigned frl; int loc; bool before; const char* noteBefore; bool wantLimiter; unsigned wantCap; const char* wantNote; int wantLines; } caps[] = {
            { "no cap in the driver",                        true,  0,   -1, false, "", false, 0,   "", 0 },
            { "a cap of 116 from the game's own profile",    true,  116, 0,  false, "", true,  116, "NVIDIA's Max Frame Rate for GTA IV is 116 fps (from GTA IV's own profile)", 1 },
            { "a cap of 60 from the global profile",         true,  60,  1,  false, "", true,  60,  "NVIDIA's Max Frame Rate for GTA IV is 60 fps (from the global profile)", 1 },
            { "a cap while FusionFix's limit is on already", true,  116, 1,  true,  "FusionFix's FPS limit is on (118 fps, x)", true, 116, "FusionFix's FPS limit is on (118 fps, x)", 0 },
            { "the reading failed",                          false, 116, 1,  false, "", false, 0,   "", 0 },
        };
        const IvtGsyncState keep = ivtGsync;
        for (auto& c : caps)
        {
            ivtGsync = IvtGsyncState{}; ivtGsync.read = c.read; ivtGsync.frl = c.frl; ivtGsync.locFrl = c.loc;
            latLimiter = c.before; strcpy_s(latLimiterNote, c.noteBefore); latNvCapFps = 0; latNvCapLoc = -1; latNvCapNote[0] = 0; g_loggedN = 0;
            LatNvCapSeen();
            LatNvCapSeen();                                  // a second reading in the same session says nothing again
            char line[300] = ""; if (c.wantLines) _snprintf_s(line, sizeof(line), _TRUNCATE, "  latency: %s: the pacer is off", c.wantNote);
            const bool ok = latLimiter == c.wantLimiter && latNvCapFps == c.wantCap && !strcmp(latLimiterNote, c.wantNote) && g_loggedN == c.wantLines && (!c.wantLines || !strcmp(g_logged[0], line));
            printf("  %s  the cap: %s -> limiter %d, cap %u, %d log line(s)%s%s\n", ok ? "ok  " : "FAIL", c.what, (int)latLimiter, latNvCapFps, g_loggedN, g_loggedN ? ": " : "", g_loggedN ? g_logged[0] : "");
            if (!ok) bad++;
        }
        ivtGsync = keep;
    }
    if (bad) { printf("THE RULE FAILED %d case(s)\n", bad); return 3; }
    return 0;
}
'''

def main():
    src = open(SRC, "rb").read().decode("utf-8")
    a = src.index(START); b = src.index(END, a)
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "gsync_read.cpp"), "wb").write((PRELUDE + src[a:b] + MAIN).encode("utf-8"))
    vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")
    cmd = 'call "%s" >nul 2>&1 && cl /nologo /EHsc /W4 /std:c++17 /O2 gsync_read.cpp /Fe:GTAIV.exe /link user32.lib' % vcvars   # user32: the primary display's name, for the VRR question (2026-10-02)
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=OUT)
    exe = os.path.join(OUT, "GTAIV.exe")
    if r.returncode != 0 or not os.path.exists(exe) or "warning C" in r.stdout:
        print(r.stdout); print(r.stderr); print("COMPILE FAILED (exit %d)" % r.returncode); return 2
    # THE NAME IS PART OF THE QUESTION: the driver finds the profile by the executable, and the mod asks with the game's own
    # path. NVIDIA's predefined entry is "gtaiv.exe" with no folder, so a GTAIV.exe anywhere matches it; the line
    # "game profile of its own: 1" is the proof it did. The test exe runs from %TEMP%, never from the owner's game folder.
    r = subprocess.run([exe], capture_output=True, text=True)
    print(r.stdout, end="")
    if r.stderr: print(r.stderr, end="")
    return r.returncode

if __name__ == "__main__":
    rc = main()
    if rc == 0: shutil.rmtree(OUT, ignore_errors=True)
    sys.exit(rc)
