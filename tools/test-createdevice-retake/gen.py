END = "// ---- END OF THE CreateDevice SLOT TAKEN BACK ----"

HOOK_DLL = r'''#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <d3d9.h>
typedef HRESULT (__stdcall *CreateDevice_t)(IDirect3D9*, UINT, D3DDEVTYPE, HWND, DWORD, D3DPRESENT_PARAMETERS*, IDirect3DDevice9**);
#ifdef HEAP
static CreateDevice_t* gOrig = nullptr;            // the original lives on the heap: this module's data holds only a heap address
#define ORIG (*gOrig)
#else
static CreateDevice_t gOrigData = nullptr;         // the original lives in this module's data, as most vtable hooks keep it
#define ORIG gOrigData
#endif
static volatile LONG gCalls = 0;
static HRESULT __stdcall Hook(IDirect3D9* d, UINT a, D3DDEVTYPE t, HWND w, DWORD f, D3DPRESENT_PARAMETERS* p, IDirect3DDevice9** o)
{
    if (InterlockedIncrement(&gCalls) > 64) return E_ABORT;   // a loop's brake, so a failing case ends instead of overflowing
    return ORIG(d, a, t, w, f, p, o);
}
extern "C" void __stdcall Read(void** vtbl)
{
#ifdef HEAP
    if (!gOrig) gOrig = (CreateDevice_t*)HeapAlloc(GetProcessHeap(), 0, sizeof(CreateDevice_t));
#endif
    ORIG = (CreateDevice_t)vtbl[16];
}
extern "C" void __stdcall Write(void** vtbl)
{
    DWORD old = 0; VirtualProtect(&vtbl[16], sizeof(void*), PAGE_READWRITE, &old);
    vtbl[16] = (void*)&Hook;
    VirtualProtect(&vtbl[16], sizeof(void*), old, &old);
}
extern "C" LONG __stdcall Calls() { return gCalls; }
#pragma comment(linker, "/EXPORT:Read=_Read@4")
#pragma comment(linker, "/EXPORT:Write=_Write@4")
#pragma comment(linker, "/EXPORT:Calls=_Calls@0")
'''

