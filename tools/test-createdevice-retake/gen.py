"""THE CreateDevice TAKE-BACK'S BENCH (2026-09-27). The region "THE CreateDevice SLOT TAKEN BACK" in source/DLSS-IV.cpp
decides, while the mod waits for the game's device, whether a module that wrote over the IDirect3D9::CreateDevice slot
goes around this mod (take the slot back, once) or passes the call on (leave it), and guards the hook against a loop.
It is cut out of the SHIPPED file at test time, never copied, and compiled into a small x86 program with a fake DXVK
vtable, a stub for the hook's body (it counts, notes its caller, and calls the original, as the real one does), and a
hook DLL that plays the other module. The DLL keeps its original in its own data, or on the heap (a second build), because
the judgement reads that module's data.

    python tools/test-createdevice-retake/gen.py        builds and runs; exit code 0 = every check passed

Needs the same Visual Studio the build uses (vswhere finds it). Writes into %TEMP%\\dlssiv-test-retake-<pid> (removed when
it passes, kept to read when it fails).
"""
