def vcvars():
    vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    return os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")

def cl(vc, args, cwd):
    r = subprocess.run('call "%s" >nul 2>&1 && cl /nologo %s' % (vc, args), shell=True, capture_output=True, text=True, cwd=cwd)
    if r.returncode != 0 or "warning C" in r.stdout:
        print(r.stdout); print(r.stderr); raise SystemExit("COMPILE FAILED: cl %s" % args)

def main():
    src = open(SRC, "rb").read().decode("utf-8")
    a = src.index(START); b = src.index(END, a)
    os.makedirs(OUT, exist_ok=True)
    vc = vcvars()
    open(os.path.join(OUT, "hook.cpp"), "w").write(HOOK_DLL)
    open(os.path.join(OUT, "t.cpp"), "wb").write((PRELUDE + src[a:b] + HARNESS).encode("utf-8"))
    cl(vc, '/LD /MT /W3 /O2 hook.cpp /Fe:hookdata.dll /Fo:hookdata.obj /link /NOIMPLIB /NOEXP', OUT)
    cl(vc, '/LD /MT /W3 /O2 /DHEAP hook.cpp /Fe:hookheap.dll /Fo:hookheap.obj /link /NOIMPLIB /NOEXP', OUT)
    cl(vc, '/MT /W4 /EHsc /O2 t.cpp /Fe:t.exe /link /INCREMENTAL:NO', OUT)   # no jump thunks: &GameCreateDevice is its code

    fails = 0
    def run(mode, dll="hookdata.dll"):
        r = subprocess.run([os.path.join(OUT, "t.exe"), mode, dll], capture_output=True, text=True, cwd=OUT, timeout=60)
        if r.returncode != 0: return "EXIT %d %s" % (r.returncode, r.stderr.strip()), []
        lines = r.stdout.strip().splitlines()
        return (lines[0] if lines else ""), lines[1:]
    def check(ok, what):
        nonlocal fails
        fails += 0 if ok else 1
        print("  %s  %s" % ("PASS" if ok else "FAIL", what))
    def show(name, head, log):
        print("%s: %s" % (name, head))
        for l in log: print("      log: " + l.strip()[:190])

    head, log = run("none"); show("no other hook", head, log)
    check("body=1 hook=0 dxvk=1 reentries=0 retaken=0 slot=t.exe ingame=1" in head, "the game's call runs the body once; the caller passed in is the game's call site, not the guard's")
    check(not log, "not a line said")

    head, log = run("thief"); show("a hook that goes around the mod (keeps its original in its data)", head, log)
    check("body=1 hook=1 dxvk=1 reentries=0 retaken=1 slot=t.exe ingame=1" in head, "TAKEN BACK: the body ran for the game's call, the other hook ran, the device was made once")
    check(any("TAKEN BACK, once" in l and "hookdata.dll" in l for l in log), "the line names the module and says TAKEN BACK")

    head, log = run("chainer"); show("a hook that passes the call on (keeps ours in its data)", head, log)
    check("body=1 hook=1 dxvk=1 reentries=0 retaken=0 slot=hookdata.dll" in head, "LEFT: the chain order is unchanged, the other hook first and this mod after it")
    check(any("keeps this mod's hook as its original" in l for l in log), "the line says it passes the call on and is left")

    head, log = run("chainer", "hookheap.dll"); show("a chainer that keeps its original on the heap", head, log)
    check("body=1 hook=1 dxvk=1 reentries=0 retaken=0 slot=hookheap.dll" in head, "LEFT when nothing in its data says: the chain works as before")
    check(any("nothing in that module's data says" in l for l in log), "the line says it cannot tell and leaves it")

    head, log = run("thief", "hookheap.dll"); show("a hook that goes around, keeping its original on the heap (the limit)", head, log)
    check("body=0 hook=1 dxvk=1 reentries=0 retaken=0" in head,"LEFT, so this miss still gets the recovery at the wait's end (the limit, as designed)")

    head, log = run("restored"); show("the slot given back its original pointer", head, log)
    check("body=1 hook=0 dxvk=1 reentries=0 retaken=1 slot=t.exe" in head, "TAKEN BACK: nothing sits between, the body runs")
    check(any("which put the original pointer back" in l for l in log), "the line says the original was put back")

    head, log = run("restored3"); show("the first pointer put back three times", head, log)
    check("body=1 hook=0 dxvk=1 reentries=0 retaken=1 slot=t.exe" in head, "TAKEN BACK each time: the game's call runs the body, the device is made once")
    check(sum("which put the original pointer back: TAKEN BACK." in l for l in log) == 1 and not any("TAKEN BACK, once" in l for l in log), "the first is said in full, and not as 'once'")
    check(sum("taken back again" in l for l in log) == 2 and not any("replaced AGAIN" in l for l in log), "the second and third are said as taken back again, none is left")

    head, log = run("layer"); show("Windows' layer: its hook in the slot first, written back three times", head, log)
    check("body=1 hook=1 dxvk=1 reentries=0 retaken=1 slot=t.exe" in head, "the game's call runs this mod's body, then the layer's hook, then DXVK: once each")
    check(sum("taken back again" in l for l in log) == 2 and any("hookdata.dll" in l and "TAKEN BACK." in l for l in log), "three take-backs, the module named")

    head, log = run("restoredmax"); show("the first pointer put back for ever (the bound)", head, log)
    check("restores=32" in head or any("restores=32" in l for l in log), "32 take-backs and no more")
    full = "\n".join([head] + log)
    check("body=0 hook=0 dxvk=1" in full, "after the bound the slot is left: the game's call goes around this mod (the recovery's case)")
    check(full.count("replaced AGAIN") == 1 and full.count("the last time, it is left after this") == 1, "the last take-back says it is the last, and the next one is said as left, once")

    head, log = run("import"); show("the game's import wrapped: the layer writes its hook back inside Direct3DCreate9, three times", head, log)
    full = "\n".join([head] + log)
    check("create9=3 restores=3" in full, "the wrapper ran for each of the three calls and took the slot back each time")
    check("body=1 hook=1 dxvk=1 reentries=0 retaken=1 slot=t.exe ingame=1" in full, "the game's CreateDevice, straight after, runs this mod's body, the layer's hook and DXVK once each")

    head, log = run("noimport"); show("the control: the same without the wrapper", head, log)
    check("body=0 hook=1 dxvk=1" in head, "the game's device is made around this mod (the miss the owner's Q1 had)")

    head, log = run("slot"); show("the import slot, by the import directory", head, log)
    check("slot=found" in head and "same=1" in head, "kernel32!GetTickCount: the slot is found and holds the function")
    check("d3d9=none wrap=0" in head and any("import of Direct3DCreate9 was not found" in l for l in log), "a module with no such import: none, nothing wrapped, and the line says so")

    head, log = run("rehook"); show("taken back, then the other module hooks again on top of us", head, log)
    check("body=1 hook=2 dxvk=1 reentries=1 retaken=1 slot=hookdata.dll" in head, "the guard ends the loop: one body, one device, the other hook twice (its own doing)")
    check(sum("replaced AGAIN" in l for l in log) == 1, "the second replacement is said once and not taken back")
    check(any("came back into this mod's hook on the same thread" in l for l in log), "the guard's line is said")

    head, log = run("late"); show("the game's device made before the look", head, log)
    check("body=0 hook=1 dxvk=1" in head and "retaken=1" in head, "the miss happened first; the take-back after it changes nothing for that device (the recovery's case)")

    head, log = run("naive"); print("the control, the same re-hook against a hook with no guard: " + head)
    check("depth 33" in head and "dxvk=0" in head and "hr=0x80004004" in head, "without the guard the two hooks call each other until the brake stops them")

    print("PASS" if fails == 0 else "FAIL: %d check(s)" % fails)
    return 0 if fails == 0 else 1

if __name__ == "__main__":
    rc = main()
    if rc == 0: shutil.rmtree(OUT, ignore_errors=True)
    sys.exit(rc)
