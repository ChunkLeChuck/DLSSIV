"""THE LADDER'S BENCH TEST (2026-09-24). Mode 4's controller (LatAdaptiveStep and its helpers in
source/transport/DlssIvTransport.h) is a state machine fed one window at a time, so it can be compiled on its own and
driven by synthetic machines: a CPU-bound one, a GPU-bound one whose pacer pays, one whose pacer ratchets after release,
a borderline one, a limiter that comes and goes, a scene change. Every transition the card could not reach on the
owner's 4090 (the pacer kept, then audited and kept or dropped) is reached here, on the SHIPPED code: the controller is
cut out of the header at test time, never copied.

    python tools/test-ladder/gen.py            builds and runs; exit code 0 = every check passed
    python tools/test-ladder/gen.py -v         also prints every log line the controller wrote

Needs the same Visual Studio the build uses (vswhere finds it). Writes into %TEMP%\\dlssiv-test-ladder-<pid> (removed when it passes, kept to read when it fails).
"""
import os, sys, subprocess, tempfile, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
HDR = os.path.join(ROOT, "source", "transport", "DlssIvTransport.h")
OUT = os.path.join(tempfile.gettempdir(), "dlssiv-test-ladder-%d" % os.getpid())   # per process (2026-09-24): parallel worktrees shared one folder and broke each other's compile
START = "// THE ADAPTIVE LADDER, MODE 4"
END = "static void LatWaiterLoop()"   # the waiter's loop follows the controller (its thread entry, LatWaiter, comes after the loop since audit F2)

PRELUDE = r'''// GENERATED by tools/test-ladder/gen.py: the controller below is cut from source/transport/DlssIvTransport.h.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <cstdio>
#include <cstring>
#include <cstdarg>
#include <string>
static struct { int log; } ivtCfg = { 2 };
static volatile LONG latAsyncWant = 1;
static volatile LONG latPaceHold  = 1;
static bool latLimiter = false, latVsync = false, latPacerOn = true;
static bool gVerbose = false;
static std::string gLog;
static int  gPaceReleases = 0, gSincePaceRelease = 0;
static void LogRecord(const char* fmt, ...)
{
    char b[640]; va_list ap; va_start(ap, fmt); _vsnprintf_s(b, sizeof(b), _TRUNCATE, fmt, ap); va_end(ap);
    gLog += b; gLog += "\n"; if (gVerbose) puts(b);
}
static void LogHealth(const char* fmt, ...)
{
    char b[640]; va_list ap; va_start(ap, fmt); _vsnprintf_s(b, sizeof(b), _TRUNCATE, fmt, ap); va_end(ap);
    gLog += b; gLog += "\n"; if (gVerbose) puts(b);
}
static void LatPaceHoldSet(bool hold)
{
    if (hold) { latPaceHold = 1; return; }
    if (!latPaceHold) return;
    latPaceHold = 0; gPaceReleases++; gSincePaceRelease = 0;   // the real one resets the estimator here
}
// ---------------------------------------------------------------- the controller, as shipped
'''

def main():
    verbose = "-v" in sys.argv
    src = open(HDR, "rb").read().decode("utf-8")
    a = src.index(START); b = src.index(END, a)
    block = src[a:b]
    # THE HELD FRAME RATE'S TWO PIECES LIVE IN DLSS-IV.cpp (2026-10-11): its names at the file's top, its two functions at its
    # end, because the header may not grow (the release's hot data). Both are cut, never copied, like the controller.
    cpp_src = open(os.path.join(ROOT, "source", "DLSS-IV.cpp"), "rb").read().decode("utf-8")
    a = cpp_src.index("// The ladder's held frame rate (defined at this file's end)."); e = "static bool AdOutOfBandHeld(float mP, bool lighterOnly);"
    names = cpp_src[a:cpp_src.index(e, a) + len(e)] + "\n"
    a = cpp_src.index("// ---- THE LADDER'S HELD FRAME RATE START"); b = cpp_src.index("// ---- THE LADDER'S HELD FRAME RATE END ----", a)
    block = names + block + cpp_src[a:b]
    scen = open(os.path.join(HERE, "scenarios.inc"), "rb").read().decode("utf-8")
    os.makedirs(OUT, exist_ok=True)
    cpp = os.path.join(OUT, "test_ladder.cpp")
    open(cpp, "wb").write((PRELUDE + block + "\n// ---------------------------------------------------------------- the bench\n" + scen).encode("utf-8"))
    vsw = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), r"Microsoft Visual Studio\Installer\vswhere.exe")
    ip = subprocess.check_output([vsw, "-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"]).decode().strip()
    vcvars = os.path.join(ip, r"VC\Auxiliary\Build\vcvars32.bat")
    exe = os.path.join(OUT, "test_ladder.exe")
    cmd = 'call "%s" >nul 2>&1 && cl /nologo /EHsc /W3 /std:c++17 /O2 test_ladder.cpp /Fe:test_ladder.exe' % vcvars
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=OUT)   # a string through the shell: a list would re-quote the paths for cmd
    if r.returncode != 0 or not os.path.exists(exe):
        print(r.stdout); print(r.stderr); print("COMPILE FAILED (exit %d)" % r.returncode); return 2
    r = subprocess.run([exe] + (["-v"] if verbose else []), capture_output=True, text=True)
    print(r.stdout, end="")
    if r.stderr: print(r.stderr, end="")
    return r.returncode

if __name__ == "__main__":
    rc = main()
    if rc == 0: shutil.rmtree(OUT, ignore_errors=True)   # a pass leaves nothing behind; a failure keeps its files to read
    sys.exit(rc)
